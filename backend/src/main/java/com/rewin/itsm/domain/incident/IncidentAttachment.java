package com.rewin.itsm.domain.incident;

import com.rewin.itsm.common.BaseEntity;
import com.rewin.itsm.domain.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * Metadata for a file attached to an incident.
 *
 * <p>The file itself lives in object storage (S3 when deployed) under
 * {@code objectKey}; only this row is in the database. The key is generated by
 * the server and never derived from the uploaded filename, so two uploads of
 * {@code screenshot.png} can never overwrite each other.
 */
@Entity
@Table(name = "incident_attachments",
    indexes = @Index(name = "ix_attachments_incident", columnList = "incident_id"),
    uniqueConstraints = @UniqueConstraint(name = "uk_attachments_object_key", columnNames = "object_key"))
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class IncidentAttachment extends BaseEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "incident_id", nullable = false, updatable = false,
        foreignKey = @ForeignKey(name = "fk_attachments_incident"))
    private Incident incident;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "uploaded_by_id", nullable = false, updatable = false,
        foreignKey = @ForeignKey(name = "fk_attachments_uploaded_by"))
    private User uploadedBy;

    @Column(name = "object_key", nullable = false, updatable = false, length = 512)
    private String objectKey;

    /** As the uploader named it, cleaned of any path. Used only for display and download. */
    @Column(name = "original_filename", nullable = false, updatable = false, length = 255)
    private String originalFilename;

    /** Decided by the server from the validated file type, not taken from the client. */
    @Column(name = "content_type", nullable = false, updatable = false, length = 127)
    private String contentType;

    @Column(name = "size_bytes", nullable = false, updatable = false)
    private long sizeBytes;

    public IncidentAttachment(Incident incident, User uploadedBy, String objectKey, String originalFilename,
                              String contentType, long sizeBytes) {
        this.incident = incident;
        this.uploadedBy = uploadedBy;
        this.objectKey = objectKey;
        this.originalFilename = originalFilename;
        this.contentType = contentType;
        this.sizeBytes = sizeBytes;
    }
}
