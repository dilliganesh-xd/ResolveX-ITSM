package com.rewin.itsm.domain.incident;

import com.rewin.itsm.common.BaseEntity;
import com.rewin.itsm.domain.enums.IncidentStatus;
import com.rewin.itsm.domain.enums.Priority;
import com.rewin.itsm.domain.enums.SlaStatus;
import com.rewin.itsm.domain.sla.SlaPolicy;
import com.rewin.itsm.domain.team.Team;
import com.rewin.itsm.domain.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.Instant;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * The central record.
 *
 * <p>{@code reference} is the human-facing incident id (INC-000123) and is what
 * appears in the UI and in conversation; the UUID primary key stays internal.
 * It is generated by the service on creation in Phase 3.
 *
 * <p>{@code slaPolicy} is captured at creation time rather than resolved on
 * read, so editing a policy later cannot retroactively change whether a past
 * incident breached.
 */
@Entity
@Table(
    name = "incidents",
    uniqueConstraints = @UniqueConstraint(name = "uk_incidents_reference", columnNames = "reference"),
    indexes = {
        @Index(name = "ix_incidents_status", columnList = "status"),
        @Index(name = "ix_incidents_priority", columnList = "priority"),
        @Index(name = "ix_incidents_reporter", columnList = "reporter_id"),
        @Index(name = "ix_incidents_assignee", columnList = "assigned_agent_id"),
        @Index(name = "ix_incidents_resolution_deadline", columnList = "resolution_deadline")
    })
@Getter
@Setter
@NoArgsConstructor
public class Incident extends BaseEntity {

    @Column(name = "reference", nullable = false, length = 24)
    private String reference;

    /**
     * The numeric part of {@link #reference}, kept as its own column so the next
     * reference can be derived with a single max() rather than by parsing
     * strings. Assigned by IncidentService on creation.
     */
    @Column(name = "reference_seq", nullable = false)
    private long referenceSeq;

    @Column(name = "title", nullable = false, length = 160)
    private String title;

    @Column(name = "description", nullable = false, columnDefinition = "text")
    private String description;

    @Column(name = "category", nullable = false, length = 60)
    private String category;

    @Column(name = "subcategory", length = 60)
    private String subcategory;

    @Enumerated(EnumType.STRING)
    @Column(name = "priority", nullable = false, length = 16)
    private Priority priority;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 24)
    private IncidentStatus status = IncidentStatus.NEW;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "reporter_id", nullable = false, foreignKey = @ForeignKey(name = "fk_incidents_reporter"))
    private User reporter;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assigned_agent_id", foreignKey = @ForeignKey(name = "fk_incidents_agent"))
    private User assignedAgent;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assigned_team_id", foreignKey = @ForeignKey(name = "fk_incidents_team"))
    private Team assignedTeam;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "sla_policy_id", foreignKey = @ForeignKey(name = "fk_incidents_sla_policy"))
    private SlaPolicy slaPolicy;

    /** When a first response is due. Stamped from the policy at creation. */
    @Column(name = "response_deadline")
    private Instant responseDeadline;

    /** When resolution is due. Stamped from the policy at creation. */
    @Column(name = "resolution_deadline")
    private Instant resolutionDeadline;

    /**
     * When the incident first received a response - an agent being assigned, or
     * an agent or admin commenting. Null until that happens.
     */
    @Column(name = "response_completed_at")
    private Instant responseCompletedAt;

    /** When resolution completed. Mirrors resolvedAt and stops the SLA clock. */
    @Column(name = "resolution_completed_at")
    private Instant resolutionCompletedAt;

    /**
     * When each stage's breach was first recorded.
     *
     * <p>These are what stop the sweep writing the same breach every minute: a
     * stage is announced once, when its marker is still null. They are stored
     * rather than derived because "the deadline has passed and nothing was done"
     * stays true forever, so it cannot itself tell us whether we have already
     * said so. Keeping the instant rather than a flag also records when the
     * breach was noticed, which is the useful half of the fact.
     */
    @Column(name = "response_breached_at")
    private Instant responseBreachedAt;

    @Column(name = "resolution_breached_at")
    private Instant resolutionBreachedAt;

    @Enumerated(EnumType.STRING)
    @Column(name = "sla_status", length = 16)
    private SlaStatus slaStatus;

    /** Required when an incident is resolved; shown on the detail page. */
    @Column(name = "resolution_summary", columnDefinition = "text")
    private String resolutionSummary;

    @Column(name = "resolved_at")
    private Instant resolvedAt;

    @Column(name = "closed_at")
    private Instant closedAt;
}
